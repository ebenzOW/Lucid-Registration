CREATE TABLE IF NOT EXISTS PERIOD (
    Period_ID INT NOT NULL,
    Start_Time TIME NOT NULL,
    End_Time TIME NOT NULL,
    PRIMARY KEY (Period_ID),
    CHECK (Start_Time < End_Time)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DAY (
    Day_ID INT NOT NULL,
    Weekday VARCHAR(15) NOT NULL,
    PRIMARY KEY (Day_ID),
    UNIQUE (Weekday)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS BUILDING (
    Building_ID INT NOT NULL,
    Building_Name VARCHAR(100) NOT NULL,
    Usage_Purpose VARCHAR(100),
    PRIMARY KEY (Building_ID),
    UNIQUE (Building_Name)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SEMESTER (
    Semester_ID INT NOT NULL,
    Semester_Name VARCHAR(20) NOT NULL,
    Semester_Year INT NOT NULL,
    Start_Date DATE NOT NULL,
    End_Date DATE NOT NULL,
    PRIMARY KEY (Semester_ID),
    UNIQUE (Semester_Name, Semester_Year),
    CHECK (End_Date >= Start_Date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS HOLDS (
    Hold_ID INT NOT NULL,
    Hold_Type VARCHAR(50) NOT NULL,
    PRIMARY KEY (Hold_ID),
    UNIQUE (Hold_Type)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS USER (
    User_ID INT NOT NULL,
    User_Type VARCHAR(20) NOT NULL,
    User_FName VARCHAR(50) NOT NULL,
    User_LName VARCHAR(50) NOT NULL,
    User_MName VARCHAR(50),
    User_Gender VARCHAR(15),
    User_DOB DATE,
    User_PhoneNo VARCHAR(15),
    Street_No VARCHAR(10),
    Street_Name VARCHAR(50),
    City VARCHAR(50),
    State VARCHAR(20),
    Country VARCHAR(50),
    Zip_Code VARCHAR(15),
    PRIMARY KEY (User_ID),
    CHECK (User_ID BETWEEN 100000 AND 9999999)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS TIME_SLOT (
    Time_Slot_ID INT NOT NULL,
    Time_Slot_Day VARCHAR(15) NOT NULL,
    Period_ID INT NOT NULL,
    PRIMARY KEY (Time_Slot_ID),
    FOREIGN KEY (Period_ID) REFERENCES PERIOD(Period_ID) ON DELETE CASCADE,
    UNIQUE (Time_Slot_Day, Period_ID)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS TIME_SLOT_DAY (
    Time_Slot_ID INT NOT NULL,
    Day_ID INT NOT NULL,
    PRIMARY KEY (Time_Slot_ID, Day_ID),
    FOREIGN KEY (Time_Slot_ID) REFERENCES TIME_SLOT(Time_Slot_ID) ON DELETE CASCADE,
    FOREIGN KEY (Day_ID) REFERENCES DAY(Day_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ROOM (
    Room_ID VARCHAR(15) NOT NULL,
    Building_ID INT NOT NULL,
    Room_NO VARCHAR(10) NOT NULL,
    Room_Type VARCHAR(20) NOT NULL,
    PRIMARY KEY (Room_ID),
    FOREIGN KEY (Building_ID) REFERENCES BUILDING(Building_ID) ON DELETE CASCADE,
    UNIQUE (Building_ID, Room_NO)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS INFORMATION_RELATION (
    Semester_ID INT NOT NULL,
    Last_Day_Of_Registration DATE NOT NULL,
    Last_Day_Of_Dropping_Course DATE NOT NULL,
    Date_Of_Midterm_Grade_Recording DATE NOT NULL,
    Date_Of_Final_Grades_Recording DATE NOT NULL,
    PRIMARY KEY (Semester_ID),
    FOREIGN KEY (Semester_ID) REFERENCES SEMESTER(Semester_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ADMIN (
    Admin_ID INT NOT NULL,
    Security_Level INT NOT NULL,
    PRIMARY KEY (Admin_ID),
    FOREIGN KEY (Admin_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LOGIN (
    User_ID INT NOT NULL,
    User_Email VARCHAR(100) NOT NULL UNIQUE,
    User_Password VARCHAR(255) NOT NULL,
    No_Login_Attempts INT NOT NULL DEFAULT 0,
    Is_Locked BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (User_ID),
    FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE,
    CHECK (No_Login_Attempts >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PASSWORD_RESET (
    User_ID INT NOT NULL,
    Reset_Code CHAR(6) NOT NULL,
    Time_Code_Sent DATETIME NOT NULL,
    PRIMARY KEY (User_ID),
    FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS USER_UPDATE_LOG (
    Log_ID INT NOT NULL AUTO_INCREMENT,
    Admin_ID INT NOT NULL,
    User_ID INT NOT NULL,
    Changed_Attribute VARCHAR(50) NOT NULL,
    Date_Of_Change DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (Log_ID),
    FOREIGN KEY (Admin_ID) REFERENCES ADMIN(Admin_ID),
    FOREIGN KEY (User_ID) REFERENCES USER(User_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LECTURE (
    Lecture_ID VARCHAR(15) NOT NULL,
    Lecture_Seats INT NOT NULL,
    PRIMARY KEY (Lecture_ID),
    FOREIGN KEY (Lecture_ID) REFERENCES ROOM(Room_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS OFFICE (
    Office_ID VARCHAR(15) NOT NULL,
    Office_Desks INT NOT NULL,
    PRIMARY KEY (Office_ID),
    FOREIGN KEY (Office_ID) REFERENCES ROOM(Room_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS LAB (
    Lab_ID VARCHAR(15) NOT NULL,
    Lab_Stations INT NOT NULL,
    PRIMARY KEY (Lab_ID),
    FOREIGN KEY (Lab_ID) REFERENCES ROOM(Room_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FACULTY (
    Faculty_ID INT NOT NULL,
    Office_ID VARCHAR(15),
    Faculty_Type VARCHAR(20) NOT NULL,
    Specialty VARCHAR(100),
    Rank VARCHAR(50),
    PRIMARY KEY (Faculty_ID),
    FOREIGN KEY (Faculty_ID) REFERENCES USER(User_ID) ON DELETE CASCADE,
    FOREIGN KEY (Office_ID) REFERENCES OFFICE(Office_ID) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FULL_TIME_FACULTY (
    Faculty_ID INT NOT NULL,
    No_Classes INT NOT NULL,
    PRIMARY KEY (Faculty_ID),
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
    CHECK (No_Classes >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PART_TIME_FACULTY (
    Faculty_ID INT NOT NULL,
    PRIMARY KEY (Faculty_ID),
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DEPARTMENT (
    Department_ID INT NOT NULL,
    Department_Name VARCHAR(100) NOT NULL,
    Department_Email VARCHAR(100) NOT NULL,
    Department_Phone VARCHAR(15) NOT NULL,
    Office_ID VARCHAR(15),
    Chair_ID INT,
    PRIMARY KEY (Department_ID),
    FOREIGN KEY (Office_ID) REFERENCES OFFICE(Office_ID) ON DELETE SET NULL,
    FOREIGN KEY (Chair_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE SET NULL,
    UNIQUE (Department_Name),
    UNIQUE (Department_Email)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DEPARTMENT_MANAGERS (
    Department_ID INT NOT NULL,
    Faculty_ID INT NOT NULL,
    Role VARCHAR(50) NOT NULL,
    PRIMARY KEY (Department_ID, Faculty_ID),
    FOREIGN KEY (Department_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE CASCADE,
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DEPARTMENT_ROSTER (
    Department_ID INT NOT NULL,
    Faculty_ID INT NOT NULL,
    Date_of_Assignment DATE NOT NULL,
    Percent_Time DECIMAL(5,2) NOT NULL,
    PRIMARY KEY (Department_ID, Faculty_ID),
    FOREIGN KEY (Department_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE CASCADE,
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MAJORS (
    Major_ID INT NOT NULL,
    Department_ID INT NOT NULL,
    Major_Name VARCHAR(100) NOT NULL,
    No_Credits_Required INT NOT NULL,
    PRIMARY KEY (Major_ID),
    FOREIGN KEY (Department_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE CASCADE,
    UNIQUE (Department_ID, Major_Name),
    CHECK (No_Credits_Required > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MINORS (
    Minor_ID INT NOT NULL,
    Department_ID INT NOT NULL,
    Minor_Name VARCHAR(100) NOT NULL,
    No_Credits_Required INT NOT NULL,
    PRIMARY KEY (Minor_ID),
    FOREIGN KEY (Department_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE CASCADE,
    UNIQUE (Department_ID, Minor_Name),
    CHECK (No_Credits_Required > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS COURSES (
    Course_ID VARCHAR(15) NOT NULL,
    Course_Type VARCHAR(20) NOT NULL,
    Course_Name VARCHAR(100) NOT NULL,
    Course_Description TEXT,
    Course_Credits INT NOT NULL,
    Department_ID INT NOT NULL,
    PRIMARY KEY (Course_ID),
    FOREIGN KEY (Department_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE CASCADE,
    CHECK (Course_Credits > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS COURSE_PREREQUISITE (
    Prerequisite_Course_ID VARCHAR(15) NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    PRIMARY KEY (Prerequisite_Course_ID, Course_ID),
    FOREIGN KEY (Prerequisite_Course_ID) REFERENCES COURSES(Course_ID) ON DELETE CASCADE,
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID) ON DELETE CASCADE,
    CHECK (Prerequisite_Course_ID <> Course_ID)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MAJOR_REQUIREMENTS (
    Major_ID INT NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    Min_Grade VARCHAR(2) NOT NULL,
    PRIMARY KEY (Major_ID, Course_ID),
    FOREIGN KEY (Major_ID) REFERENCES MAJORS(Major_ID) ON DELETE CASCADE,
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MINOR_REQUIREMENTS (
    Minor_ID INT NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    Min_Grade VARCHAR(2) NOT NULL,
    PRIMARY KEY (Minor_ID, Course_ID),
    FOREIGN KEY (Minor_ID) REFERENCES MINORS(Minor_ID) ON DELETE CASCADE,
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS STUDENT (
    Student_ID INT NOT NULL,
    Student_Year INT NOT NULL,
    Student_Type VARCHAR(20) NOT NULL,
    Dept_ID INT,
    Credits_Earned INT DEFAULT 0,
    PRIMARY KEY (Student_ID),
    FOREIGN KEY (Student_ID) REFERENCES USER(User_ID) ON DELETE CASCADE,
    FOREIGN KEY (Dept_ID) REFERENCES DEPARTMENT(Department_ID) ON DELETE SET NULL,
    CHECK (Student_Year > 0),
    CHECK (Credits_Earned >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS GRADUATE_STUDENT (
