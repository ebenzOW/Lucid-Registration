CREATE TABLE IF NOT EXISTS ADVISOR_STUDENT (
    Faculty_ID INT NOT NULL,
    Student_ID INT NOT NULL,
    Date_Assigned DATE NOT NULL,
    PRIMARY KEY (Faculty_ID, Student_ID),
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS COURSE_SECTIONS (
    CRN INT NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    Section_Number INT NOT NULL,
    Faculty_ID INT NOT NULL,
    Time_Slot_ID INT NOT NULL,
    Room_ID VARCHAR(15) NOT NULL, 
    Semester_ID INT NOT NULL,
    Available_seats INT NOT NULL,
    PRIMARY KEY (CRN),
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID) ON DELETE CASCADE,
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
    FOREIGN KEY (Time_Slot_ID) REFERENCES TIME_SLOT(Time_Slot_ID) ON DELETE RESTRICT,
    FOREIGN KEY (Room_ID) REFERENCES ROOM(Room_ID) ON DELETE RESTRICT,
    FOREIGN KEY (Semester_ID) REFERENCES SEMESTER(Semester_ID) ON DELETE RESTRICT,
    UNIQUE (Course_ID, Section_Number, Semester_ID),
    UNIQUE (Time_Slot_ID, Room_ID, Semester_ID), -- Stops duplicates in the same time and place
    CHECK (Section_Number > 0),
    CHECK (Available_Seats >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ENROLLMENT (
    CRN INT NOT NULL,
    Student_ID INT NOT NULL,
    Grade VARCHAR(2),
    PRIMARY KEY (CRN, Student_ID),
    FOREIGN KEY (CRN) REFERENCES COURSE_SECTIONS(CRN) ON DELETE CASCADE,
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FACULTY_HISTORY (
    Faculty_ID INT NOT NULL,
    CRN INT NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    Semester_ID INT NOT NULL,
    PRIMARY KEY (Faculty_ID, CRN),
    FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
    FOREIGN KEY (CRN) REFERENCES COURSE_SECTIONS(CRN) ON DELETE RESTRICT,
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID),
    FOREIGN KEY (Semester_ID) REFERENCES SEMESTER(Semester_ID)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS STUDENT_HISTORY (
    Student_ID INT NOT NULL,
    CRN INT NOT NULL,
    Course_ID VARCHAR(15) NOT NULL,
    Semester_ID INT NOT NULL,
    Grade VARCHAR(2) NOT NULL,
    PRIMARY KEY (Student_ID, CRN),
    FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE,
    FOREIGN KEY (CRN) REFERENCES COURSE_SECTIONS(CRN) ON DELETE RESTRICT,
    FOREIGN KEY (Course_ID) REFERENCES COURSES(Course_ID),
    FOREIGN KEY (Semester_ID) REFERENCES SEMESTER(Semester_ID)
) ENGINE=InnoDB;